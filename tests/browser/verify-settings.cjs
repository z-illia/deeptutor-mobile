const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.SETTINGS_BASE_URL || 'http://localhost:8099';
const simulation = process.env.SETTINGS_SIM_URL;
assert.ok(simulation, 'Provide SETTINGS_SIM_URL including its routeKey.');
(async () => {
  const browser = await chromium.launch({ executablePath: process.env.CHROME_EXECUTABLE || '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addInitScript(server => localStorage.setItem('deeptutor-api-server', server), base);
    const config = data => context.request.post(`${simulation}/__test/config`, { data });
    const state = async () => (await context.request.get(`${simulation}/__test/state`)).json();
    await context.request.post(`${simulation}/__test/reset`);
    const requests = [], commands = [];
    await context.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url()); requests.push(url.pathname);
      const response = await context.request.fetch(`${simulation}${url.pathname}${url.search}`, { method: req.method(), data: req.postDataBuffer() ?? undefined, headers: req.postDataBuffer() ? { 'content-type': 'application/json' } : {} });
      await route.fulfill({ response });
    });
    await context.routeWebSocket(url => new URL(url).pathname === '/ws', socket => socket.onMessage(raw => {
      const command = JSON.parse(String(raw)); commands.push(command);
      if (command.type === 'check_active_turn') socket.send(JSON.stringify({ protocol_version: '2.0', type: 'active_turn_info', status: 'idle' }));
    }));
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const copy = require('../../src/i18n/locales/en.json');
    const button = name => page.getByRole('button', { name: copy[name] ?? name, exact: true });
    const choose = async (label, value) => { await button(label).click(); await button(value).click(); };
    const local = () => page.evaluate(() => JSON.parse(localStorage.getItem('deeptutor-mobile-local-v1')).state);
    await config({ failure: 'load' });
    await page.goto(`${base}/settings/general`); await page.waitForURL('**/settings/general');
    await page.getByText('Test settings unavailable', { exact: true }).first().waitFor({ timeout: 60000 });
    await config({}); await button('Retry').click();
    await button('Interface language').waitFor();
    await choose('Model output language', 'Français');
    await choose('Interface layout', 'Classic');
    await button('Save draft').click();
    await page.getByTestId('settings-phase').filter({ hasText: copy['Draft not applied yet'] }).waitFor();
    assert.equal((await state()).ui.response_language, 'pl');
    assert.equal((await local()).layout, 'modern');
    await button('Appearance').click();
    await choose('Theme', 'Cream');
    await choose('Learning text size', '125%');
    await choose('Line spacing', 'Relaxed');
    await choose('Code syntax theme', 'A11Y Dark');
    await page.getByRole('switch', { name: copy['Show line numbers'], exact: true }).click();
    await page.getByRole('switch', { name: copy['Wrap long lines'], exact: true }).click();
    await config({ failure: 'save' }); await button('Save draft').click();
    await page.getByText('Test settings unavailable', { exact: true }).first().waitFor();
    assert.equal((await state()).ui.theme, 'snow');
    await config({}); await button('Save draft').click();
    await page.getByTestId('settings-phase').filter({ hasText: copy['Draft not applied yet'] }).waitFor();
    await page.reload(); await button('Theme').waitFor();
    assert.equal(await button('Theme').innerText(), 'Cream');
    assert.equal((await local()).theme, 'snow');
    await config({ failure: 'ui' }); await button('Apply changes').click();
    await page.getByText('Test settings unavailable', { exact: true }).first().waitFor();
    assert.equal((await local()).theme, 'snow');
    await config({ failure: 'clear' }); await button('Apply changes').click();
    await page.getByText('Settings applied, but the draft could not be cleared. Retry Apply.', { exact: true }).waitFor();
    assert.equal((await state()).ui.theme, 'light');
    assert.equal((await local()).theme, 'cream');
    const uiWrites = (await state()).uiWrites.length;
    await config({}); await button('Apply changes').click();
    await button('Apply changes').waitFor({ state: 'hidden' });
    let server = await state();
    assert.equal(server.uiWrites.length, uiWrites);
    assert.equal((await local()).layout, 'classic');
    assert.deepEqual(server.draft.extensions, { tools: { enabled: ['search'] }, ui: { sidebar_description: 'Keep draft sidebar' } });
    assert.equal(server.ui.sidebar_description, 'Keep live sidebar');
    assert.equal(requests.includes('/api/settings/apply'), false);
    await page.goto(`${base}/chat/seed-session`);
    await page.getByTestId('markdown-code-block').waitFor();
    assert.equal(await page.getByText('Learning sample', { exact: true }).evaluate(node => parseFloat(getComputedStyle(node).fontSize)), 17.5);
    await page.getByLabel('1', { exact: true }).waitFor();
    await page.getByLabel('Message', { exact: true }).fill('Language test'); await button('Send').click();
    await page.waitForTimeout(100);
    assert.equal(commands.find(command => command.type === 'start_turn').language, 'fr');
    await page.goto(`${base}/settings/appearance`); await button('Theme').waitFor();
    await page.getByRole('switch', { name: copy['Wrap long lines'], exact: true }).click();
    await config({ failure: 'clear' }); await button('Discard').click();
    await page.getByText('Test settings unavailable', { exact: true }).first().waitFor();
    await config({}); await button('Discard').click();
    await button('Discard').waitFor({ state: 'hidden' });
    assert.equal(await page.getByRole('switch', { name: copy['Wrap long lines'], exact: true }).isChecked(), true);
    await config({ externalDraft: true });
    await page.getByRole('switch', { name: copy['Wrap long lines'], exact: true }).click();
    await button('Save draft').click();
    await page.getByText('Settings changed on the server. Reload before saving.', { exact: true }).waitFor();
    await config({}); await button('Refresh').click();
    const dialog = page.getByRole('dialog', { name: 'Reload settings?', exact: true });
    await dialog.getByRole('button', { name: copy.Refresh, exact: true }).click();
    await button('Theme').waitFor();
    assert.equal(await button('Theme').innerText(), 'Glass');
    assert.equal((await local()).theme, 'cream');
    await config({ user: 'another-user' });
    await page.reload(); await button('Theme').waitFor();
    assert.equal((await local()).appliedSettings.responseLanguage, 'pl');
    assert.equal((await local()).theme, 'snow');
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Passed: load/retry, cross-page draft, persistence, no premature apply, UI/cleanup failures, recovery without duplicate UI writes, foreign draft preservation, local layout, response language, rendered text/code, conflict detection, account isolation.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
