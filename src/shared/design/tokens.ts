export type Palette = Record<keyof typeof basePalettes.snow, string>;
export type ThemeChoice = "system" | "snow" | "cream" | "dark" | "glass";
export type LayoutChoice = "modern" | "classic";
export function resolveDesign(choice: ThemeChoice, layout: LayoutChoice, system: string | null | undefined) {
  const name = choice === 'system' ? (system === 'dark' ? 'dark' : 'snow') : choice;
  const dark = name === 'dark' || name === 'glass';
  const colors: Palette = { ...basePalettes[name], ...(name === 'snow' && layout === 'modern' ? modernSnow : {}) };
  const shadows = modernShadows[dark ? 'dark' : 'light'];
  if (layout === 'modern' && name === 'snow') colors.shadowRaised = shadows.md;
  for (const key of Object.keys(colors) as (keyof Palette)[]) colors[key] = nativeCss(colors[key]);
  return { name, colors, dark, shadows: Object.fromEntries(Object.entries(shadows).map(([key, value]) => [key, nativeCss(value)])), layout };
}
