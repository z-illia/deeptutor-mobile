const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.SEARCH_BASE_URL || 'http://localhost:8100';
const simulation = process.env.SEARCH_SIM_URL;
assert.ok(simulation, 'Provide SEARCH_SIM_URL including routeKey.');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addInitScript(server => localStorage.setItem('deeptutor-api-server', server), base);
    await context.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url());
      const response = await context.request.fetch(`${simulation}${url.pathname}${url.search}`, { method: req.method(), data: req.postDataBuffer() ?? undefined, headers: req.postDataBuffer() ? { 'content-type': 'application/json' } : {} });
      await route.fulfill({ response });
    });
    await context.routeWebSocket(url => new URL(url).pathname === '/ws', socket => socket.onMessage(raw => {
      if (JSON.parse(String(raw)).type === 'check_active_turn') socket.send(JSON.stringify({ protocol_version: '2.0', type: 'active_turn_info', status: 'idle' }));
    }));
    await context.request.post(`${simulation}/__test/reset`);
    const config = async data => {
      await context.request.post(`${simulation}/__test/config`, { data });
      assert.deepEqual((await (await context.request.get(`${simulation}/__test/state`)).json()).options, data);
    };
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const button = name => page.getByRole('button', { name, exact: true });
    const input = () => page.getByRole('textbox', { name: require('../../src/i18n/locales/en.json')['navigation.searchEverything'], exact: true });
    await page.goto(`${base}/ui/search?q=equation`);
    await page.waitForURL('**/search?q=equation');
    await button('Server equation 0').waitFor({ timeout: 60000 });
    assert.equal(await input().inputValue(), 'equation');
    assert.equal(await button('Mathematics · session A').count(), 0);
    await button('Equation learning').waitFor(); await button('Equation coach').waitFor(); await button('Equation group').waitFor();
    await page.getByText('A remembered equation inside a persisted message', { exact: true }).first().waitFor();
    await page.screenshot({ path: '/tmp/search-mobile.png' });
    await button('Load more').click();
    await button('Server equation 54').waitFor();
    assert.equal(await button('Load more').count(), 0);
    const state = await (await context.request.get(`${simulation}/__test/state`)).json();
    assert.ok(state.requests.some(row => row.path.endsWith('/search') && row.query.offset === '50' && row.query.dt_workspace === ''));
    await input().fill('slow'); await page.waitForTimeout(350);
    await input().fill('fast'); await button('Server fast 0').waitFor();
    await page.waitForTimeout(1000);
    assert.equal(await button('Server slow 0').count(), 0);
    assert.equal(await button('Server equation 0').count(), 0);
    await config({ failure: 'partners' });
    await input().fill('equation');
    await button('Server equation 0').waitFor();
    await page.getByText('Partners: Partner service unavailable', { exact: true }).waitFor();
    assert.equal(await button('Equation coach').count(), 0);
    await config({}); await button('Retry').click(); await button('Equation coach').waitFor();
    await config({ failure: 'sessions' }); await input().fill('geometry');
    await page.getByText('Conversations: Search service unavailable', { exact: true }).waitFor();
    await button('Equation learning').waitFor();
    assert.equal(await button('Server equation 0').count(), 0);
    await config({ failure: 'unauthorized' }); await button('Retry').click();
    await page.waitForURL('**/login?*');
    assert.equal(new URL(page.url()).searchParams.get('next'), '/search?q=geometry');
    await config({ failure: 'missing' }); await page.goto(`${base}/search?q=geometry`);
    await page.getByText('Conversations: Search is not available on this server.', { exact: true }).waitFor();
    await config({ failure: 'malformed' }); await button('Retry').click();
    await page.getByText('Conversations: Invalid search data received from the server.', { exact: true }).waitFor();
    await config({}); await button('Retry').click(); await button('Server geometry 0').waitFor();
    await input().fill('nothing-matches');
    await page.getByText('No matching records', { exact: true }).waitFor();
    await input().fill(''); await button('Server recent 0').waitFor();
    const count = (await (await context.request.get(`${simulation}/__test/state`)).json()).requests.length;
    await page.goto(`${base}/search?q=${'x'.repeat(201)}`);
    await page.getByText('Search query must be 200 characters or fewer.', { exact: true }).waitFor();
    await page.waitForTimeout(400);
    assert.equal((await (await context.request.get(`${simulation}/__test/state`)).json()).requests.length, count);
    await page.goto(`${base}/mobile/26`); await button('Search library').click();
    await page.waitForURL('**/search'); await input().fill('fast');
    await button('Server fast 0').click();
    await page.waitForURL('**/chat/general-fast-0');
    await page.goto(`${base}/mobile/62`); await button('Workspace B').click(); await button('Use selected workspace').click();
    await page.waitForURL('**/learning');
    await page.goto(`${base}/search?q=equation`);
    await button('Workspace B equation 0').waitFor();
    assert.equal(await button('Server equation 0').count(), 0);
    await page.setViewportSize({ width: 320, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Passed: legacy alias/query, real HTTP full-text hits, pagination, stale cancellation, partial failures, retry, 401/404/malformed responses, empty/recent queries, query limit, library entry, exact session link and workspace isolation.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
