const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const base = process.env.RESOURCES_BASE_URL || 'http://localhost:8101';
const simulation = process.env.RESOURCES_SIM_URL;
assert.ok(simulation, 'Provide RESOURCES_SIM_URL including routeKey.');
(async () => {
  const browser = await chromium.launch({ executablePath: '/opt/google/chrome/chrome', headless: true, args: ['--no-sandbox'] });
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } });
    await context.addInitScript(server => localStorage.setItem('deeptutor-api-server', server), base);
    await context.route('**/api/**', async route => {
      const req = route.request(), url = new URL(req.url());
      const response = await context.request.fetch(`${simulation}${url.pathname}${url.search}`, { method: req.method(), data: req.postDataBuffer() ?? undefined, headers: req.postDataBuffer() ? { 'content-type': 'application/json' } : {} });
      await route.fulfill({ response });
    });
    await context.request.post(`${simulation}/__test/reset`);
    const config = async data => { await context.request.post(`${simulation}/__test/config`, { data }); assert.deepEqual((await (await context.request.get(`${simulation}/__test/state`)).json()).options, data); };
    const page = await context.newPage(); page.setDefaultTimeout(15000);
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const button = name => page.getByRole('button', { name, exact: true });
    const count = key => page.getByTestId(`count-${key}`);
    const expectCount = async (key, value) => { await count(key).filter({ hasText: new RegExp(`^${value}$`) }).waitFor({ timeout: 60000 }); };
    await page.goto(`${base}/personalization`); await page.waitForURL('**/mobile/65');
    for (const [key, value] of Object.entries({ personas: 7, skills: 11, partners: 4, agents: 3, mcp: 2, cli_apps: 1 })) await expectCount(key, value);
    assert.equal((await page.locator('body').innerText()).includes('0 of 8 connected'), false);
    await page.screenshot({ path: '/tmp/resource-personalization.png' });
    await config({ slow: '/api/personas', zero: true }); await button('Refresh').click();
    await expectCount('skills', 0); await expectCount('personas', 'Loading…'); await expectCount('personas', 7);
    await config({ failure: '/api/personas', forbidden: true }); await button('Refresh').click();
    await expectCount('personas', 'Unavailable'); await expectCount('skills', 11);
    await page.getByText('This page is not available for your account.', { exact: true }).waitFor();
    await config({ malformed: '/api/space/mcp/servers' }); await button('Refresh').click();
    await expectCount('mcp', 'Unavailable'); await expectCount('personas', 7);
    await config({ updated: true }); await button('Refresh').click(); await expectCount('personas', 9);
    await config({ user: 'other-user', slow: '/api/personas' }); await page.reload();
    await expectCount('personas', 'Loading…'); assert.equal(await count('personas').innerText(), 'Loading…'); await expectCount('personas', 1);
    await config({ user: 'other-user' });
    await page.goto(`${base}/mobile/26`);
    for (const [key, value] of Object.entries({ chat_history: 203, notebooks: 3, knowledge: 4, question_bank: 301 })) await expectCount(key, value);
    const state = await (await context.request.get(`${simulation}/__test/state`)).json();
    assert.ok(state.requests.some(row => row.path === '/api/sessions' && row.query.offset === '200' && row.query.dt_workspace === ''));
    const accountPaths = ['/api/personas', '/api/skills/list', '/api/partners/navigation', '/api/subagents/connections', '/api/space/mcp/servers', '/api/space/cli-apps/apps'];
    assert.ok(state.requests.filter(row => accountPaths.includes(row.path)).every(row => row.query.dt_workspace === undefined));
    await button('Notebook').waitFor();
    await button('Switch workspace').waitFor();
    await button('Account and settings').waitFor();
    await page.screenshot({ path: '/tmp/resource-library.png' });
    await config({ user: 'other-user', failure: '/api/sessions' }); await button('Refresh').click();
    await expectCount('chat_history', 'Unavailable'); await expectCount('knowledge', 4);
    await config({ user: 'other-user' }); await button('Refresh').click(); await expectCount('chat_history', 203);
    await page.goto(`${base}/mobile/62`); await button('Workspace B').click(); await button('Use selected workspace').click(); await page.waitForURL('**/learning');
    await page.goto(`${base}/mobile/26`);
    for (const key of ['chat_history', 'notebooks', 'knowledge', 'question_bank']) await expectCount(key, 0);
    await page.goto(`${base}/mobile/65`); await expectCount('personas', 1);
    await page.setViewportSize({ width: 320, height: 844 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
    assert.deepEqual(errors, []);
    console.log('Passed: source-derived counters, complete session pagination, independent loading, zero vs failure, malformed/403 recovery, refresh, user/workspace isolation, account scope, personal MCP ownership and granted/enabled CLI filtering.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
