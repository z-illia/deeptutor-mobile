// Resolve CSS alpha mixes at the shared boundary; never introduce a substitute palette.
export function alpha(color: string, opacity: number) {
  if (color.startsWith('#') && color.length === 7) {
    return `rgba(${parseInt(color.slice(1, 3), 16)}, ${parseInt(color.slice(3, 5), 16)}, ${parseInt(color.slice(5, 7), 16)}, ${opacity})`;
  }
  const rgba = color.match(/^rgba?\(([^)]+)\)$/);
  if (rgba) { const channels = rgba[1].split(/[,/ ]+/).filter(Boolean).map(Number); return `rgba(${channels[0]}, ${channels[1]}, ${channels[2]}, ${(channels[3] ?? 1) * opacity})`; }
  return color;
}

// Equivalent comma syntax avoids React Native Web treating CSS Color 4 values as black.
export function nativeCss(value: string) {
  return value.replace(/rgb\((\d+) (\d+) (\d+) \/ ([\d.]+)\)/g, 'rgba($1, $2, $3, $4)');
}
